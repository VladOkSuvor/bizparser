"""Стадии воронки CRM. Один статус = одна стадия, без дублей смысла.

Список задан здесь один раз: бэкенд валидирует по нему, фронт получает его
через /api/meta, цвета — CSS-переменные --st-<key> в web/static/style.css.
"""

from __future__ import annotations

# key -> (подпись, что делать дальше). Порядок = порядок в воронке.
STATUSES: dict[str, tuple[str, str]] = {
    "new": ("Новий", "лід ще не набирали"),
    "in_progress": ("В роботі", "дзвонимо / пишемо, ще без результату"),
    "no_answer": ("Недодзвон", "не взяли слухавку — набрати ще раз"),
    "interested": ("Зацікавлений", "домовились про демо"),
    "demo_done": ("Демо показано", "демо відбулось, чекаємо рішення"),
    "won": ("Закрито (угода)", "оплатив / підписав"),
    "lost": ("Відмова", "явне «ні», більше не набирати"),
}

# В БД «Новий» хранится как NULL: так не надо проставлять статус 1.5k лидам
# и новые записи из discover сразу оказываются в «Новий»
DEFAULT = "new"


def label(key: str | None) -> str:
    return STATUSES[key or DEFAULT][0]
